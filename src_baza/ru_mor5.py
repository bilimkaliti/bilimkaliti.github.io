ONE = ['один', 'одна', 'одно']; TWO = ['два', 'две', 'два']
def nn_form(n, w, g, g2, g5):
    l = n % 10; l2 = n % 100
    base = {20: 'двадцать', 21: 'двадцать', 22: 'двадцать', 23: 'двадцать', 24: 'двадцать', 25: 'двадцать'}
    def word(k, gg):
        if k == 1: return ONE[gg]
        if k == 2: return TWO[gg]
        return NUM[k]
    if n <= 20 and n not in (21, 22):
        if n == 1: return f'{ONE[g]} {w}'
        if n == 2: return f'{TWO[g]} {g2}'
        if n in (3, 4): return f'{NUM[n]} {g2}'
        return f'{NUM[n]} {g5}'
    t = n - l; tw = NUM[t]
    if l == 1: return f'{tw} {ONE[g]} {w}'
    if l == 2: return f'{tw} {TWO[g]} {g2}'
    if l in (3, 4): return f'{tw} {NUM[l]} {g2}'
    return f'{tw} {NUM[l]} {g5}' if l else f'{tw} {g5}'
def sgo(n, w, g, g2, g5):
    r = nn_form(n, w, g, g2, g5); parts = r.split(); head = ' '.join(parts[:-1])
    pool = [x for x in {f'{head} {w}', f'{head} {g2}', f'{head} {g5}'} if x != r]
    extra = []
    for m in R.sample([k for k in range(1, 40) if k != n], 30):
        c = nn_form(m, w, g, g2, g5)
        if c != r and c.split()[-1] == parts[-1] and c not in extra and c not in pool: extra.append(c)
        if len(pool) + len(extra) >= 3: break
    return mc(f'Выберите правильную форму: {n} ({w})', r, (pool + extra)[:3])
