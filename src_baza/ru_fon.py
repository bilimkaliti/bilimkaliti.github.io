# ---- Слог
def s1():
    w = ch(WORDS); n = vl(w); return mc(f'Сколько слогов в слове «{w}»?', str(n), wr([str(x) for x in range(1, 7)], str(n)))
def s2():
    n = ch([1, 2, 3, 4]); ws = [w for w in WORDS if vl(w) == n]
    if len(ws) < 1: return None
    w = ch(ws); other = [x for x in WORDS if vl(x) != n]
    return mc(f'В каком слове {["один", "два", "три", "четыре"][n-1]} слог{"а" if n in (2,3,4) else ""}?', w, R.sample(other, 3))
def s3():
    t = R.randrange(3); w = ch(WORDS); n = vl(w)
    if t == 0: return mc('Сколько в слове слогов?', 'Столько, сколько в нём гласных', ['Столько, сколько согласных', 'Столько, сколько всех букв', 'Всегда два'])
    same = [x for x in WORDS if vl(x) == n and x != w]; less = [x for x in WORDS if vl(x) != n]
    if t == 1 and same: return mc(f'Какое слово имеет столько же слогов, сколько слово «{w}»?', ch(same), R.sample(less, 3))
    more = [x for x in WORDS if vl(x) > n]; ok = [x for x in WORDS if vl(x) <= n and x != w]
    if t == 2 and more and len(ok) >= 3: return mc(f'В каком слове слогов больше, чем в слове «{w}»?', ch(more), R.sample(ok, 3))
    return None
