NM = {'стол': ['стола', 'столу', 'стол', 'столом', 'столе'], 'дом': ['дома', 'дому', 'дом', 'домом', 'доме'], 'город': ['города', 'городу', 'город', 'городом', 'городе'],
      'урок': ['урока', 'уроку', 'урок', 'уроком', 'уроке'], 'сад': ['сада', 'саду', 'сад', 'садом', 'саду']}
NM['сад'][4] = 'саде'
AF = ['нов', 'красив', 'интересн', 'светл']
EF = ['ой', 'ой', 'ую', 'ой', 'ой']; EM = ['ого', 'ому', 'ый', 'ым', 'ом']
FR_ = [('У меня нет ___.', 0), ('Я подхожу к ___.', 1), ('Я вижу ___.', 2), ('Я доволен ___.', 3), ('Я говорю о ___.', 4)]
def mk(frame, case, noun, forms, ends, a):
    right = f'{a}{ends[case]} {forms[case]}'
    wrong = []
    for j in range(5):
        if j != case:
            x = f'{a}{ends[j]} {forms[j]}'
            if x != right and x not in wrong: wrong.append(x)
    wrong += [f'{a}{ends[case]} {forms[(case + 1) % 5]}']
    return mc(f'Выберите правильную форму: {frame} ({a}{"ая" if ends is EF else "ый"} {noun})', right, [w for w in wrong if w != right])
def pk1():
    n = ch(list(NF)); f, c = ch(FR_); a = ch(AF); return mk(f, c, n, NF[n], EF, a)
def pk2():
    n = ch(list(NM)); f, c = ch(FR_); a = ch(AF)
    if c == 2: return None
    return mk(f, c, n, NM[n], EM, a)
B.topic(BM, 'r_sklpr', 'Склонение прилагательных — Sifat kelishigi', [6, 7, 8], pk1, lambda: ch([pk1, pk2])(), lambda: ch([pk2, pk2, pk1])(), 'склонение прилагательных kelishik')

