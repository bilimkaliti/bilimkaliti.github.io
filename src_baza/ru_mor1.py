# ---- Падежи (вопросы)
CQ = [('Именительный падеж', 'кто? что?'), ('Родительный падеж', 'кого? чего?'), ('Дательный падеж', 'кому? чему?'), ('Винительный падеж', 'кого? что?'), ('Творительный падеж', 'кем? чем?'), ('Предложный падеж', 'о ком? о чём?')]
CASES = [x for x, _ in CQ]
CS = [('Мама читает книгу.', 'мама', 0), ('Мама читает книгу.', 'книгу', 3), ('Я иду к другу.', 'другу', 2), ('Он пишет ручкой.', 'ручкой', 4), ('Мы живём в городе.', 'городе', 5),
      ('У меня нет брата.', 'брата', 1), ('Я дарю маме цветы.', 'маме', 2), ('Я дарю маме цветы.', 'цветы', 3), ('Книга лежит на столе.', 'столе', 5), ('Мы говорим о школе.', 'школе', 5),
      ('Он работает врачом.', 'врачом', 4), ('Я вижу птицу.', 'птицу', 3), ('Это дом моего друга.', 'друга', 1), ('Я пишу письмо подруге.', 'подруге', 2), ('Девочка рисует карандашом.', 'карандашом', 4),
      ('Мы приехали из Ташкента.', 'Ташкента', 1), ('Брат ушёл без шапки.', 'шапки', 1), ('Весна пришла.', 'весна', 0), ('Ребёнок спит в кроватке.', 'кроватке', 5), ('Я скучаю по маме.', 'маме', 2),
      ('Он гордится сыном.', 'сыном', 4), ('В сумке лежит тетрадь.', 'сумке', 5), ('Мальчик идёт из школы.', 'школы', 1)]
def tag(x, w):
    i = x.lower().index(w.lower()); return x[:i] + '«' + x[i:i + len(w)] + '»' + x[i + len(w):]
SN = [(tag(x, w), i) for x, w, i in CS]
PRED = ['именительном', 'родительном', 'дательном', 'винительном', 'творительном', 'предложном']
def c1():
    c, q = ch(CQ); i = CASES.index(c)
    if R.random() < .5: return mc(f'На какие вопросы отвечает {c.lower()}?', q, R.sample([y for x, y in CQ if y != q], 3))
    return mc(f'Какой падеж отвечает на вопросы «{q}»?', c, wr(CASES, c))
def c2():
    i = R.randrange(6); good = [x for x, j in SN if j == i]; bad = [x for x, j in SN if j != i]
    if not good: return None
    return mc(f'В каком предложении выделенное слово стоит в {PRED[i]} падеже?', ch(good), R.sample(bad, 3))
def c3():
    s, w, i = ch(CS); return mc(f'В каком падеже слово «{w}» в предложении: {s}', CASES[i], wr(CASES, CASES[i]))
B.topic(BM, 'r_padej', 'Падежи — Kelishiklar', [6, 7, 8], c1, c3, c2, 'падежи padej kelishik')
