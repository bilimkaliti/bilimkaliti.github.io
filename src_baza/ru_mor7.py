PART = {'читать': 'читающий', 'писать': 'пишущий', 'играть': 'играющий', 'любить': 'любящий', 'говорить': 'говорящий', 'смотреть': 'смотрящий', 'слышать': 'слышащий', 'держать': 'держащий',
        'знать': 'знающий', 'стоять': 'стоящий', 'спать': 'спящий', 'бежать': 'бегущий', 'думать': 'думающий', 'плавать': 'плавающий', 'рисовать': 'рисующий', 'строить': 'строящий'}
PASS = ['прочитанный', 'написанный', 'построенный', 'решённый', 'увиденный', 'сделанный', 'нарисованный', 'выученный']
NOTP = ['красивый', 'добрый', 'стол', 'читать', 'читает', 'книга', 'большой', 'быстро', 'читая', 'написав']
def pa1():
    return mc('Какое слово — причастие?', ch(list(PART.values()) + PASS), R.sample(NOTP, 3))
def pa2():
    v = ch(list(PART)); return mc(f'Образуйте действительное причастие настоящего времени от глагола «{v}».', PART[v], wr(list(PART.values()), PART[v]))
def pa3():
    p = ch(list(PART.values())); v = [k for k, x in PART.items() if x == p][0]; return mc(f'От какого глагола образовано причастие «{p}»?', v, wr(list(PART), v))
