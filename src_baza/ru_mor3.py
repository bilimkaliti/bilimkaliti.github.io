# ---- Личные местоимения
PP = {'я': ['меня', 'мне', 'меня', 'мной', 'обо мне'], 'ты': ['тебя', 'тебе', 'тебя', 'тобой', 'о тебе'], 'он': ['его', 'ему', 'его', 'им', 'о нём'], 'она': ['её', 'ей', 'её', 'ей', 'о ней'],
      'мы': ['нас', 'нам', 'нас', 'нами', 'о нас'], 'вы': ['вас', 'вам', 'вас', 'вами', 'о вас'], 'они': ['их', 'им', 'их', 'ими', 'о них']}
FRM = [('У ___ нет книги.', 0, 'род.'), ('Я дам ___ книгу.', 1, 'дат.'), ('Я вижу ___.', 2, 'вин.'), ('Он гордится ___.', 3, 'тв.'), ('Мы говорим ___.', 4, 'предл.')]
def pq(p, c):
    f = FRM[c][0]; alt = [x for x in sorted(set(PP[p])) if x != PP[p][c]]
    pad = [PP[q][c] for q in PP if q != p and PP[q][c] not in alt and PP[q][c] != PP[p][c]]
    alt += R.sample(pad, max(0, 3 - len(alt))); alt = alt[:] if len(alt) <= 3 else R.sample(alt, 3)
    return mc(f'Выберите форму местоимения «{p}»: {f}', PP[p][c], alt)
def pp1(): return pq(ch(['я', 'ты', 'мы', 'вы']), R.randrange(5))
def pp2(): return pq(ch(['он', 'она', 'они']), R.randrange(5))
def pp3(): return pq(ch(list(PP)), R.randrange(5))
B.topic(BM, 'r_lichn', 'Личные местоимения — Kishilik olmoshlari', [5, 6, 7, 8], pp1, pp2, pp3, 'личные местоимения olmosh')

POS = {'мой': ['мой', 'моя', 'моё', 'мои'], 'твой': ['твой', 'твоя', 'твоё', 'твои'], 'наш': ['наш', 'наша', 'наше', 'наши'], 'ваш': ['ваш', 'ваша', 'ваше', 'ваши']}
PN = [('дом', 0), ('книга', 1), ('окно', 2), ('книги', 3), ('школа', 1), ('письмо', 2), ('друг', 0), ('тетради', 3), ('город', 0), ('море', 2), ('сестра', 1), ('друзья', 3)]
def pos1():
    p = ch(list(POS)); n, g = ch(PN); pr = {'мой': 'я', 'твой': 'ты', 'наш': 'мы', 'ваш': 'вы'}[p]
    return mc(f'Выберите местоимение: Это ___ {n}. (принадлежит: {pr})', POS[p][g], wr(POS[p], POS[p][g]))
def pos2():
    t = R.randrange(3)
    if t == 0: p, n = ch([('Али', 'его'), ('Лола', 'её'), ('Али и Лола', 'их')]); return None
    n, g = ch(PN); p = ch(list(POS)); return mc(f'Какая форма местоимения «{p}» подходит: ___ {n}?', POS[p][g], wr(POS[p], POS[p][g]))
def pos3():
    who, ans = ch([('Это Али. Это ___ книга.', 'его'), ('Это Лола. Это ___ книга.', 'её'), ('Это Али и Лола. Это ___ дом.', 'их'), ('Это Анвар. Это ___ друг.', 'его'), ('Это Зарина. Это ___ сестра.', 'её'),
                   ('Это мои друзья. Это ___ школа.', 'их'), ('Это мама. Это ___ сумка.', 'её'), ('Это папа. Это ___ машина.', 'его')])
    return mc(f'Выберите местоимение: {who}', ans, wr(['его', 'её', 'их', 'ихний'], ans))
B.topic(BM, 'r_prit', 'Притяжательные местоимения — Egalik olmoshlari', [5, 6, 7, 8], pos1, lambda: ch([pos1, pos3])(), lambda: ch([pos3, pos1])(), 'притяжательные местоимения egalik')

