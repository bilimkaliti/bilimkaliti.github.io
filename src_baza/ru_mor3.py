VS = {'читать': 'чита', 'играть': 'игра', 'работать': 'работа', 'думать': 'дума', 'писать': 'писа', 'рисовать': 'рисова', 'слушать': 'слуша', 'смотреть': 'смотре', 'учить': 'учи', 'ждать': 'жда'}
EN = ['л', 'ла', 'ло', 'ли']
def pt1():
    s, g = ch(SUBJ); v = ch(list(VS)); return mc(f'Выберите правильную форму: {s} ___ ({v}).', VS[v] + EN[g], [VS[v] + e for e in EN if e != EN[g]])
def pt2():
    s, g = ch(SUBJ); v = ch(list(VS)); return mc(f'Вчера {s.lower()} ___ ({v}).', VS[v] + EN[g], [VS[v] + e for e in EN if e != EN[g]])
def pt3():
    t = R.randrange(2)
    if t == 0: g = R.randrange(4); return mc(f'Окончание «-{EN[g]}» в глаголе прошедшего времени показывает:', ['мужской род', 'женский род', 'средний род', 'множественное число'][g], [x for x in ['мужской род', 'женский род', 'средний род', 'множественное число'] if x != ['мужской род', 'женский род', 'средний род', 'множественное число'][g]])
    g = R.randrange(4); v = ch(list(VS)); cand = [s for s, h in SUBJ if h == g]; bad = [s for s, h in SUBJ if h != g]
    return mc(f'С каким словом подходит форма «{VS[v] + EN[g]}»?', ch(cand), R.sample(bad, 3))
